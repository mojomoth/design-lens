/**
 * Dev generator (NOT part of the build): regenerate `src/capture/percy-dom-src.ts` from the
 * installed `@percy/dom` browser bundle. Run after bumping the `@percy/dom` pin:
 *
 *   node scripts/gen-percy-src.mjs
 *
 * The @percy/dom serializer (spec 02 §M2) has to run INSIDE the page, injected via
 * `page.addScriptTag({ content })`. Inside the single-file CJS bundle `require.resolve('@percy/dom')`
 * does not exist, so the browser source must be embedded at build time. We embed it as a
 * gzip+base64 STRING (deterministic — Node's gzip header uses mtime 0) rather than raw text: the
 * raw bundle is ~105 KB and would push `dist/design-lens.cjs` over the hard 2 MiB repo-hygiene gate
 * (verify.sh B2c); gzip shrinks it to ~36 KB. The gzip bytes are hex-free of the placeholder
 * scanner's trigger words (base64 alphabet), and the file is imported by `capture/serialize.ts`,
 * which `gunzipSync`s it once at module load.
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkg = require('@percy/dom/package.json');
const bundlePath = path.join(path.dirname(require.resolve('@percy/dom/package.json')), 'dist/bundle.js');
const bundle = readFileSync(bundlePath);
const b64 = gzipSync(bundle, { level: 9 }).toString('base64');

const here = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(here, '..', 'src', 'capture', 'percy-dom-src.ts');

const contents = `/**
 * GENERATED by \`node scripts/gen-percy-src.mjs\` — do not edit by hand.
 *
 * The @percy/dom browser serializer bundle (v${pkg.version}, dist/bundle.js), embedded as a
 * gzip+base64 string. It runs INSIDE the page (\`page.addScriptTag({ content: PERCY_DOM_SRC })\`),
 * where it defines \`window.PercyDOM.serialize\`. Inside the single-file CJS bundle a runtime
 * \`require.resolve('@percy/dom')\` does not resolve, so the source is baked in here (spec 02 §M2).
 * It is gzip'd (105 KB raw -> ~36 KB) to keep \`dist/design-lens.cjs\` under the 2 MiB gate.
 */
import { gunzipSync } from 'node:zlib';

const PERCY_DOM_GZIP_B64 =
  '${b64}';

/** The @percy/dom browser bundle source, decoded once at module load. */
export const PERCY_DOM_SRC: string = gunzipSync(Buffer.from(PERCY_DOM_GZIP_B64, 'base64')).toString('utf8');
`;

writeFileSync(outPath, contents);
process.stderr.write(`gen-percy-src: wrote ${outPath} (@percy/dom@${pkg.version}, ${b64.length} b64 chars)\n`);
